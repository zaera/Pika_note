"""Pack the reviewed manager HTML into firmware without changing any routes."""
from pathlib import Path
import gzip,re,hashlib
root=Path(__file__).resolve().parent.parent
page=(root/'tools/manager.html').read_text(encoding='utf-8')
css=(root/'tools/portal.css').read_bytes()
tag=hashlib.sha256(css).hexdigest()[:12]
packed=gzip.compress(css,mtime=0)
asset='// Generated from tools/portal.css.\n#pragma once\nstatic const uint8_t kPortalCssGzip[] PROGMEM = {\n'
for i in range(0,len(packed),24):asset+=','.join(map(str,packed[i:i+24]))+',\n'
asset+='};\nstatic const char* kPortalCssTag = "'+tag+'";\n'
css_header=root/'pika_note/src/app/portal_assets.h'
if not css_header.exists() or css_header.read_text(encoding='ascii')!=asset:css_header.write_text(asset,encoding='ascii')
device=page.replace('href="portal.css"','href="/portal.css?v='+tag+'"')
compressed=gzip.compress(device.encode('utf-8'),mtime=0)
header='// Generated by tools/pack_manager.py.\n#pragma once\nstatic const uint8_t kManagerGzip[] PROGMEM = {\n'
for i in range(0,len(compressed),24):header+=','.join(map(str,compressed[i:i+24]))+',\n'
header+='};\n'
target=root/'pika_note/src/app/manager_assets.h'
if not target.exists() or target.read_text(encoding='ascii')!=header:target.write_text(header,encoding='ascii')
print('Manager packed:',len(device.encode()),'->',len(compressed),'bytes')
