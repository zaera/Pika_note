"""Generate the supplemental GNU FreeSans glyphs; ASCII uses original Adafruit tables."""
from pathlib import Path
from PIL import ImageFont

root = Path(__file__).resolve().parent.parent
out = ['// Generated by tools/generate_cyrillic.py from GNU FreeFont 20120503.\n#pragma once\n']
for name, source, size in [('CyrSans9','FreeSans.ttf',18),('CyrSansBold9','FreeSansBold.ttf',18),('CyrSansBold12','FreeSansBold.ttf',24),('CyrSansBold18','FreeSansBold.ttf',36)]:
    font=ImageFont.truetype(str(root/'tools/font-source'/source),size)
    bitmap=[]; glyphs=[]
    for code in range(0x400,0x500):
        ch=chr(code)
        mask,offset=font.getmask2(ch,mode='1',anchor='ls')
        width,height=mask.size
        bits=[1 if v else 0 for v in mask]
        glyphs.append((len(bitmap),width,height,round(font.getlength(ch)),*offset))
        for i in range(0,len(bits),8):
            chunk=bits[i:i+8]+[0]*max(0,i+8-len(bits))
            bitmap.append(sum(v<<(7-j) for j,v in enumerate(chunk)))
    assert len(bitmap)<65536
    out.append(f'const uint8_t {name}Bitmaps[] PROGMEM = {{\n')
    for i in range(0,len(bitmap),24):out.append(','.join(map(str,bitmap[i:i+24]))+',\n')
    out.append('};\n'+f'const GFXglyph {name}Glyphs[] PROGMEM = {{\n')
    out.extend('{'+','.join(map(str,g))+'},\n' for g in glyphs)
    out.append('};\n'+f'const GFXfont {name} PROGMEM = {{(uint8_t*){name}Bitmaps,(GFXglyph*){name}Glyphs,0x400,0x4FF,{size+3}}};\n')
(root/'pika_note/src/app/cyrillic_fonts.h').write_text(''.join(out),encoding='utf-8')
print('Supplemental FreeSans Cyrillic generated')
