"""Build the offline guide and optional Markdown wiki from docs/help-content.json."""
from pathlib import Path
import argparse
import html
import json
import re

ROOT = Path(__file__).resolve().parents[1]


def render(markdown):
    output, paragraph, items = [], [], []
    def flush():
        if paragraph:
            output.append('<p>' + html.escape(' '.join(paragraph)) + '</p>')
            paragraph.clear()
        if items:
            output.append('<ul>' + ''.join('<li>' + html.escape(x) + '</li>' for x in items) + '</ul>')
            items.clear()
    for line in markdown.splitlines() + ['']:
        if line.startswith('## '):
            flush()
            output.append('<h3>' + html.escape(line[3:]) + '</h3>')
        elif line.startswith('- ') or re.match(r'^\d+\. ', line):
            if paragraph:
                flush()
            items.append(re.sub(r'^(?:- |\d+\. )', '', line))
        elif not line.strip():
            flush()
        else:
            if items:
                flush()
            paragraph.append(line)
    return ''.join(output)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--wiki', type=Path)
    args = parser.parse_args()
    chapters = json.loads((ROOT / 'docs/help-content.json').read_text(encoding='utf-8'))
    cards = []
    for chapter in chapters:
        slug, title = chapter['slug'], chapter['title']
        cards.append('<details name="help-chapters" class="help-chapter card" id="help-' + slug + '"><summary>' + html.escape(title) + '</summary><div class="help-prose">' + render(chapter['markdown']) + '</div></details>')
        if args.wiki:
            args.wiki.mkdir(parents=True, exist_ok=True)
            (args.wiki / (slug + '.md')).write_text('# ' + title + '\n\n[в†ђ Wiki home](Home.md)\n\n' + chapter['markdown'] + '\n', encoding='utf-8')
    toc = '<nav class="help-topics" aria-label="Help topics">' + ''.join('<button class="btn" type="button" data-help-topic="help-' + c['slug'] + '">' + html.escape(c['title']) + '</button>' for c in chapters) + '</nav>'
    markup = '<section class="help-page"><div class="help-intro card"><span class="help-mark" aria-hidden="true"></span><p class="sub">A LITTLE GUIDANCE</p><h1>Help.</h1><p>Your Pika, at your pace. Start here, or jump to the detail you need.</p><small>V7 В· Available offline</small></div>' + toc + '<label class="help-search-label" for="help-search">Find in this guide</label><input class="search" type="search" id="help-search" placeholder="Try pairing, backup, mail or buttonsвЂ¦"><div class="help-chapters">' + ''.join(cards) + '</div><p id="help-no-results" class="helper" hidden>No matching topics. Try another word.</p><button class="btn" type="button" data-tab="setup">Back to Config</button></section>'
    script = '/* Generated by tools/build_help.py. Edit docs/help-content.json. */\nwindow.renderPikaHelp=()=>'+json.dumps(markup, ensure_ascii=False)+';\n'
    script += "document.addEventListener('click',e=>{const b=e.target.closest('[data-help-topic]');if(!b)return;const d=document.getElementById(b.dataset.helpTopic);if(d){const input=document.getElementById('help-search');if(input)input.value='';document.querySelectorAll('.help-chapter').forEach(c=>c.hidden=false);const empty=document.getElementById('help-no-results');if(empty)empty.hidden=true;d.open=true;d.scrollIntoView({behavior:'smooth',block:'start'})}});\n"
    script += "document.addEventListener('toggle',e=>{const d=e.target;if(!d.matches?.('.help-chapter')||!d.open)return;document.querySelectorAll('.help-chapter[open]').forEach(other=>{if(other!==d)other.open=false})},true);\n"
    script += "document.addEventListener('input',e=>{if(e.target.id!=='help-search')return;const terms=e.target.value.toLowerCase().trim().split(/\\s+/).filter(Boolean);let count=0;document.querySelectorAll('.help-chapter').forEach(c=>{const text=c.textContent.toLowerCase();c.hidden=!terms.every(t=>text.includes(t));if(!c.hidden){count++;if(terms.length)c.open=false}});document.getElementById('help-no-results').hidden=count>0});\n"
    (ROOT / 'android-companion/app/src/main/assets/help.js').write_text(script, encoding='utf-8')
    print(f'Built {len(chapters)} offline Help chapters')


if __name__ == '__main__':
    main()
